#!/usr/bin/env python3
"""Regenerate kb/INDEX.md and the counts block in README.md from the kb/ files, so published numbers always match the content.
usage: python3 tools/kb/build_index.py"""
import os, re, collections
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
def parse(p):
    t = open(p).read(); m = re.match(r"---\n(.*?)\n---\n", t, re.S); fm = {}
    for l in m.group(1).splitlines():
        if ": " in l:
            k, v = l.split(": ", 1); v = v.strip(); fm[k] = [x.strip() for x in v[1:-1].split(",")] if v.startswith("[") else v.strip('"')
    return fm
C = []
for dp, _, fn in os.walk(os.path.join(ROOT, "kb")):
    for f in sorted(fn):
        if f.endswith(".md") and f != "INDEX.md": fm = parse(os.path.join(dp, f)); fm["file"] = os.path.relpath(os.path.join(dp, f), ROOT); C.append(fm)
C.sort(key=lambda c: (c["pillar"], c["id"]))
SEV = ["critical", "high", "medium", "low", "info"]; P = sorted({c["pillar"] for c in C}); auto = sum(c["automated"] == "yes" for c in C)
tags = collections.Counter(t for c in C for t in c["tags"])
NSRC = len({i for l in [os.path.join(ROOT, "docs", "sources.md")] + [os.path.join(ROOT, "docs", "sources.d", f) for f in os.listdir(os.path.join(ROOT, "docs", "sources.d")) if f.endswith(".md")] for i in re.findall(r"^\| (S-[A-Z0-9\-]+) \|", open(l).read(), re.M)})
counts = [f"| Pillars | **{len(P)}** |", f"| Security checks | **{len(C)}** |", f"| Run automatically by the site checker | **{auto}** |", f"| Manual (server access, sign-in or human review) | **{len(C)-auto}** |", f"| Tags | **{len(tags)}** |", f"| Public sources cited | **{NSRC}** |"]
per = ["| Pillar | Checks | Critical | High | Medium | Low | Automated |", "|---|---:|---:|---:|---:|---:|---:|"]
for p in P:
    x = [c for c in C if c["pillar"] == p]; per.append(f"| [`{p}`](kb/{p}/) | {len(x)} | " + " | ".join(str(sum(c['severity'] == s for c in x) or "") for s in SEV[:4]) + f" | {sum(c['automated']=='yes' for c in x)}/{len(x)} |")
per.append(f"| **Total** | **{len(C)}** | " + " | ".join(f"**{sum(c['severity']==s for c in C) or ''}**" for s in SEV[:4]) + f" | **{auto}/{len(C)}** |")
block = "| Measured from `kb/` | Count |\n|---|---:|\n" + "\n".join(counts) + "\n\n" + "\n".join(per)
r = open(os.path.join(ROOT, "README.md")).read()
r = re.sub(r"<!-- COUNTS:START -->.*<!-- COUNTS:END -->", "<!-- COUNTS:START -->\n" + block + "\n<!-- COUNTS:END -->", r, flags=re.S)
open(os.path.join(ROOT, "README.md"), "w").write(r)
idx = ["# Check index", "", f"{len(C)} checks in {len(P)} pillars. Generated by `tools/kb/build_index.py`; do not edit by hand.", ""]
for p in P:
    idx += [f"## {p}", "", "| ID | Check | Severity | Target | Method | Tool | Auto | Tags |", "|---|---|---|---|---|---|---|---|"]
    for c in [c for c in C if c["pillar"] == p]:
        idx.append(f"| [{c['id']}]({os.path.relpath(c['file'], 'kb')}) | {c['title']} | {c['severity']} | {c['target']} | {c['method']} | `{c['tool']}` | {'yes' if c['automated']=='yes' else 'manual'} | " + " ".join(f"`{t}`" for t in c["tags"]) + " |")
    idx.append("")
idx += ["## Tags", "", " ".join(f"`{t}` ({n})" for t, n in sorted(tags.items(), key=lambda x: (-x[1], x[0]))), ""]
open(os.path.join(ROOT, "kb", "INDEX.md"), "w").write("\n".join(idx))
print(f"{len(C)} checks, {len(P)} pillars, {auto} automated, {len(tags)} tags")
